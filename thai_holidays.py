def _to_date(d):
    if isinstance(d, datetime):
        return d.date()
    if isinstance(d, date):
        return d
    t = str(d or '').strip()[:10]
    try:
        return date.fromisoformat(t)
    except ValueError:
        return None


@lru_cache(maxsize=16)
def _pkg_year(year: int) -> frozenset:
    """ปีนอกตาราง : ลองแพ็กเกจ holidays · ไม่มีแพ็กเกจคืนชุดว่าง"""
    try:
        import holidays
        h = holidays.Thailand(years=year, categories=('public', 'government'))
        return frozenset(d for d, n in h.items() if 'labour' not in str(n).lower()
                         and 'แรงงาน' not in str(n) and "children" not in str(n).lower())
    except Exception:
        return frozenset()


def holiday_name(d) -> str:
    """ชื่อวันหยุดราชการ · ไม่ใช่วันหยุดคืน '' (ไม่นับเสาร์-อาทิตย์)"""
    dd = _to_date(d)
    if dd is None:
        return ''
    k = dd.isoformat()
    if k in _EXTRA:
        return _EXTRA[k]
    if dd.year in _TABLE_YEARS:
        return _TABLE.get(k, '')
    return 'วันหยุดราชการ' if dd in _pkg_year(dd.year) else ''


def is_thai_holiday(d) -> bool:
    return bool(holiday_name(d))


def is_on_call_day(d) -> bool:
    """วันเวร on call ทั้งวัน = เสาร์ อาทิตย์ หรือวันหยุดราชการ · อ่านวันที่ไม่ออกคืน False"""
    dd = _to_date(d)
    if dd is None:
        return False
    return dd.weekday() >= 5 or is_thai_holiday(dd)


def holidays_between(date_from, date_to) -> list:
    """วันหยุดราชการที่ตกวันจันทร์-ศุกร์ในช่วง (ISO string เรียงวัน) : ใช้กรองใน SQL"""
    a, b = _to_date(date_from), _to_date(date_to)
    if a is None or b is None:
        return []
    out = []
    from datetime import timedelta
    d = a
    while d <= b:
        if d.weekday() < 5 and is_thai_holiday(d):
            out.append(d.isoformat())
        d += timedelta(days=1)
    return out
